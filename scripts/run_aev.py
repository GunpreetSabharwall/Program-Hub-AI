#!/usr/bin/env python3
"""Run Agentic Earned Value (AEV) on every initiative's source repo (Feature 22, hub mode).

Program Hub reads each initiative's source repo; so does AEV. Nothing is
installed in the source repos. For each initiative whose config.yml has an
`aev:` block in hub mode, this script:

1. builds AEV's settings from the initiative config: budget and rates from
   `aev:`, plan dates from `week_start` and `duration_weeks`, teams from `pods`
   (so Program Hub and AEV always agree on dates and teams);
2. runs AEV on `source_repo`, with the cost files kept in
   initiatives/<slug>/aev/hours.csv and agent-costs.csv (owned by the PMO,
   not by the engineering team);
3. writes AEV's outputs back into initiatives/<slug>/aev/:
   aev.json (read by aev_value.py and the dashboard), AEV-REPORT.md, badge.json.

    AEV_HOME=path/to/agentic-earned-value OCTO_PAT=... python scripts/run_aev.py
    python scripts/run_aev.py --only lakeshore-supplier-portal --as-of 2026-11-10

The token must be able to read every source repo (OCTO_PAT; see
docs/REPO-REQUIREMENTS.md). In the workflow, AEV_HOME is a checkout of the
AEV repository at a release tag.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import List, Optional

import yaml

import aev_value

ROOT = Path(__file__).parent.parent
GENERATED_NAME = "settings.generated.yml"
REQUIRED = ("budget_at_completion", "value_per_point", "hourly_rate")
PASSED_THROUGH = ("budget_at_completion", "value_per_point", "hourly_rate", "stabilization_window_days",
                  "agent_accounts", "agent_label", "currency_symbol", "start_date", "end_date")


class SetupError(ValueError):
    pass


def _to_date(value) -> date:
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    return date.fromisoformat(str(value).strip())


def aev_settings_for(cfg: dict) -> dict:
    """AEV's config.yml content, built from the initiative config."""
    raw = cfg.get("aev") or {}
    missing = [k for k in REQUIRED if raw.get(k) in (None, "")]
    if missing:
        raise SetupError(f"aev: in initiatives/{cfg['slug']}/config.yml is missing {', '.join(missing)}.")
    settings = {k: raw[k] for k in PASSED_THROUGH if raw.get(k) not in (None, "")}
    if "start_date" not in settings:
        if not cfg.get("week_start"):
            raise SetupError(f"initiatives/{cfg['slug']}/config.yml needs week_start (or aev.start_date).")
        settings["start_date"] = _to_date(cfg["week_start"]).isoformat()
    if "end_date" not in settings:
        weeks = int(cfg.get("duration_weeks") or 0)
        if weeks <= 0:
            raise SetupError(f"initiatives/{cfg['slug']}/config.yml needs duration_weeks (or aev.end_date).")
        settings["end_date"] = (_to_date(settings["start_date"]) + timedelta(weeks=weeks)).isoformat()
    for key in ("start_date", "end_date"):
        settings[key] = _to_date(settings[key]).isoformat()
    teams = {p.get("name") or p["slug"]: p["label"] for p in cfg.get("pods") or [] if p.get("label")}
    if teams:
        settings["teams"] = teams
    return settings


def write_settings(cfg: dict) -> Path:
    folder = aev_value.hub_folder(cfg)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / GENERATED_NAME
    header = (f"# GENERATED by scripts/run_aev.py from initiatives/{cfg['slug']}/config.yml; do not edit.\n"
              f"# AEV settings for {cfg['source_repo']}. Edit the aev: block and pods in config.yml instead.\n")
    path.write_text(header + yaml.safe_dump(aev_settings_for(cfg), sort_keys=False), encoding="utf-8")
    return path


def aev_command(cfg: dict, settings: Path, as_of: Optional[str] = None,
                snapshot: Optional[str] = None) -> List[str]:
    folder = aev_value.hub_folder(cfg)
    cmd = [sys.executable, "-m", "aev", "--repo", cfg["source_repo"], "--config", str(settings),
           "--hours", str(folder / "hours.csv"), "--agent-costs", str(folder / "agent-costs.csv"),
           "--output", str(folder / "AEV-REPORT.md"), "--json", str(folder / "aev.json"),
           "--badge", str(folder / "badge.json")]
    if as_of:
        cmd += ["--as-of", as_of]
    if snapshot:
        cmd += ["--snapshot", snapshot]
    return cmd


def hub_initiatives(only: Optional[str] = None) -> List[dict]:
    out = []
    for cfg in aev_value.load_configs():
        s = aev_value.aev_settings(cfg)
        if s["enabled"] and s["mode"] == "hub" and (only is None or cfg["slug"] == only):
            out.append(cfg)
    return out


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Run AEV on each initiative's source repo.")
    parser.add_argument("--only", help="Only this initiative slug.")
    parser.add_argument("--as-of", help="Calculate as of this date (YYYY-MM-DD). Default: today.")
    parser.add_argument("--snapshot", help="Offline: read issue data from this AEV snapshot file "
                                           "instead of GitHub (needs --only).")
    args = parser.parse_args(argv)
    if args.snapshot and not args.only:
        parser.error("--snapshot needs --only")

    aev_home = os.environ.get("AEV_HOME")
    if not aev_home or not (Path(aev_home) / "src" / "aev").is_dir():
        print("Set AEV_HOME to a checkout of https://github.com/GunpreetSabharwall/agentic-earned-value",
              file=sys.stderr)
        return 2
    token = os.environ.get("OCTO_PAT") or os.environ.get("GITHUB_TOKEN") or ""
    env = {**os.environ, "PYTHONPATH": str(Path(aev_home) / "src"), "GITHUB_TOKEN": token}

    failed = []
    for cfg in hub_initiatives(args.only):
        slug = cfg["slug"]
        try:
            settings = write_settings(cfg)
        except SetupError as exc:
            print(f"::error::{slug}: {exc}")
            failed.append(slug)
            continue
        print(f"{slug}: running AEV on {cfg['source_repo']}")
        result = subprocess.run(aev_command(cfg, settings, args.as_of, args.snapshot), env=env, capture_output=True, text=True)
        if result.returncode != 0:
            print(f"::error::{slug}: AEV failed: {result.stderr.strip() or result.stdout[-500:]}")
            failed.append(slug)
            continue
        print(f"{slug}: wrote initiatives/{slug}/aev/aev.json and AEV-REPORT.md")
    if failed:
        print(f"AEV failed for: {', '.join(failed)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
